import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { readFileSync, readdirSync } from 'node:fs';
import { PGlite } from '@electric-sql/pglite';
import { initialStore } from '../backend/repository';

test('operator access, atomic activity, reversible policy, expiry and owner isolation', { timeout: 60000 }, async () => {
 const db = new PGlite();
 try {
  await db.exec(`create role anon;create role authenticated;create role service_role bypassrls;
    create schema cron;create table cron.job(jobid serial primary key,jobname text unique,command text);
    create table cron.job_run_details(end_time timestamptz);
    create function cron.schedule(text,text,text) returns bigint language sql as $$insert into cron.job(jobname,command)values($1,$3)on conflict(jobname)do update set command=$3 returning jobid::bigint$$;`);
  for (const name of readdirSync('supabase/migrations').sort()) {
   if (name.includes('restrict_platform_trigger')) continue;
   await db.exec(readFileSync('supabase/migrations/' + name, 'utf8').replace(/create extension if not exists pg_cron with schema pg_catalog;/g, '').replace(/do \$\$ begin\n  if not exists\(select 1 from pg_extension where extname='pg_cron'\)[\s\S]*?end; \$\$;/, ''));
  }
  const operator = randomUUID(), owner = randomUUID();
  await db.query('select public.lothuus_operator_bootstrap($1)', [operator]);
  await db.query('select public.lothuus_operator_bootstrap($1)', [operator]);
  await assert.rejects(db.query('select public.lothuus_operator_bootstrap($1)', [owner]), /OPERATOR_ALREADY_CONFIGURED/);
  const one = async <T>(sql: string, params: unknown[] = []) => (await db.query<{ value: T }>(sql, params)).rows[0].value;
  const policy = () => one<{ count: number; limit: number; enforced: boolean }>('select public.lothuus_capacity_policy() as value');
  const report = (before: string | null = null) => one<{ activity: { id: string; kind: string; actor: string; details: { fields?: string[] } }[] }>('select public.lothuus_operator_report($1,$2) as value', [operator, before]);
  const change = (version: number, enforced: boolean, limit: number | null = null, until: string | null = null) => db.query('select public.lothuus_operator_policy($1,$2,$3,$4,$5,$6)', [operator, version, enforced, limit, until, 'Geïsoleerde test']);
  assert.equal(await one('select public.lothuus_operator_enabled($1) as value', [owner]), false);
  await assert.rejects(db.query('select public.lothuus_operator_report($1)', [owner]), /OPERATOR_FORBIDDEN/);
  await assert.rejects(db.query('select public.lothuus_operator_policy($1,1,false,null,null,$2)', [owner, 'Verboden']), /OPERATOR_FORBIDDEN/);
  assert.deepEqual(await policy(), { count: 0, limit: 200, enforced: true });
  await change(1, false);
  assert.equal((await policy()).enforced, false);
  const state = initialStore();
  state.items = Array.from({ length: 201 }, (_, n) => ({ id: randomUUID(), title: `Object ${n}`, description: 'PRIVATE_DESCRIPTION', category: 'objecten', date: '', material: '', dimensions: '', maker: '', condition: '', priceCents: 1000, publication: 'draft', photos: [], version: 1, createdAt: new Date().toISOString() })) as typeof state.items;
  const commit = async () => {
   const revision = await one<number>('select revision as value from app_private.store where id');
   return one<boolean>('select public.lothuus_commit_state_audited($1,$2,$3) as value', [revision, JSON.stringify(state), owner]);
  };
  assert.equal(await commit(), true);
  assert.equal((await policy()).count, 201);
  const first = (await report()).activity;
  assert.equal(first.length, 50);
  assert.ok(first.every((row, i) => i === 0 || BigInt(first[i-1].id) > BigInt(row.id)));
  assert.ok(first.some(row => row.kind === 'product_created')); assert.equal(first[0].actor, 'Eigenaar');
  assert.equal(JSON.stringify(first).includes('PRIVATE_DESCRIPTION'), false);
  const next = (await report(first.at(-1)!.id)).activity;
  assert.ok(next.every(row => BigInt(row.id) < BigInt(first.at(-1)!.id)));
  await change(2, true);
  state.items[0].title = 'Gewijzigd boven de limiet'; state.items[0].priceCents = 1250;
  assert.equal(await commit(), true);
  const updated = (await report()).activity[0];
  assert.equal(updated.kind, 'product_updated'); assert.ok(updated.details.fields?.includes('priceCents'));
  const beforeCount = await one<number>('select count(*)::int as value from app_private.operator_activity');
  assert.equal(await commit(), true);
  assert.equal(await one('select count(*)::int as value from app_private.operator_activity'), beforeCount);
  state.items.push({ ...state.items[0], id: randomUUID() });
  await assert.rejects(commit(), /HOSTING_OBJECT_LIMIT/);
  assert.equal((await policy()).count, 201);
  assert.equal(await one('select count(*)::int as value from app_private.operator_activity'), beforeCount);
  await change(3, true, 250, new Date(Date.now() + 3600000).toISOString());
  assert.equal(await commit(), true);
  assert.equal((await policy()).limit, 250);
  await db.exec("update app_private.operator_settings set expires_at=now()-interval '1 minute' where id");
  assert.deepEqual(await policy(), { count: 202, limit: 200, enforced: true });
  await assert.rejects(change(3, false), /OPERATOR_VERSION_CONFLICT/);
  await db.query("select public.lothuus_record_activity($1,'capacity_denied')", [owner]);
  await db.query("select public.lothuus_record_activity($1,'capacity_denied')", [owner]);
  assert.equal(await one("select count(*)::int as value from app_private.operator_activity where kind='capacity_denied'"), 1);
  const order = randomUUID();
  await db.query("insert into app_private.hosting_orders(id,product,cents,status,payload,extra) values($1,'extra50',2500,'payment_review','isolated-payload',50)", [order]);
  await db.query('select public.lothuus_operator_activate($1,$2,$3,true)', [operator, order, 'Geïsoleerde bankreferentie']);
  await db.query('select public.lothuus_operator_activate($1,$2,$3,true)', [operator, order, 'Geïsoleerde bankreferentie']);
  assert.equal((await policy()).limit, 250);
  assert.equal(await one("select count(*)::int as value from app_private.operator_activity where kind='payment_activated'"), 1);
  await db.exec('set role anon');
  for (const query of ['select public.lothuus_capacity_policy()', `select public.lothuus_operator_report('${operator}')`, 'select * from app_private.operator_activity']) await assert.rejects(db.exec(query), /permission denied/);
  await db.exec('reset role;set role authenticated');
  await assert.rejects(db.query('select public.lothuus_operator_policy($1,4,false,null,null,$2)', [operator, 'Poging']), /permission denied/);
  await db.exec('reset role');
  await db.query('update app_private.operator_users set enabled=false where user_id=$1', [operator]);
  await db.query('select public.lothuus_operator_bootstrap($1)', [operator]);
  await assert.rejects(report(), /OPERATOR_FORBIDDEN/);
 } finally { await db.close(); }
});
