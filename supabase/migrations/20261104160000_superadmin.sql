-- Extend v2 snapshots; the application also accepts earlier 15-table snapshots.
create or replace function public.lothuus_backup_state() returns jsonb
language plpgsql stable security invoker set search_path='' as $$
declare tables jsonb:='{}'; rows jsonb; t text;
begin
 foreach t in array array['store','media','product_numbers','stock_claims','heart_settings','heart_objects','heart_days',
 'analytics_config','analytics_days','hosting_account','hosting_orders','hosting_entitlements','hosting_media_objects','hosting_metrics','hosting_usage_daily',
 'operator_users','operator_settings','operator_activity'] loop
  execute format('select coalesce(jsonb_agg(to_jsonb(t)),''[]''::jsonb) from app_private.%I t',t) into rows;
  tables:=tables||jsonb_build_object(t,rows);
 end loop;
 return jsonb_build_object('schemaVersion',2,'createdAt',now(),'tables',tables);
end; $$;

do $$ declare f record; begin
 for f in select p.oid::regprocedure as signature from pg_proc p join pg_namespace n on n.oid=p.pronamespace
  where (n.nspname='public' and p.proname in ('lothuus_operator_enabled','lothuus_operator_bootstrap','lothuus_capacity_policy','lothuus_record_activity','lothuus_commit_state_audited','lothuus_operator_report','lothuus_operator_policy','lothuus_operator_activate'))
   or (n.nspname='app_private' and p.proname in ('operator_audit_store','hosting_check_capacity')) loop
  execute format('revoke all on function %s from public,anon,authenticated',f.signature);
  execute format('grant execute on function %s to service_role',f.signature);
 end loop;
end; $$;
