 user_id uuid primary key, email text not null unique, enabled boolean not null default true, created_at timestamptz not null default now()
);
create table if not exists app_private.operator_settings (
 id boolean primary key default true check(id), enforce_limit boolean not null default true,
 object_limit integer check(object_limit between 1 and 100000), expires_at timestamptz,
 version integer not null default 1, updated_at timestamptz not null default now()
);
insert into app_private.operator_settings(id) values(true) on conflict do nothing;
create table if not exists app_private.operator_activity (
 id bigint generated by default as identity primary key, at timestamptz not null default now(), actor_id uuid,
 kind text not null, object_id text, title text not null default '', details jsonb not null default '{}', dedupe_key text unique
);
create index if not exists operator_activity_at on app_private.operator_activity(at);
alter table app_private.operator_users enable row level security;
alter table app_private.operator_settings enable row level security;
alter table app_private.operator_activity enable row level security;
revoke all on app_private.operator_users,app_private.operator_settings,app_private.operator_activity from public,anon,authenticated;
grant all on app_private.operator_users,app_private.operator_settings,app_private.operator_activity to service_role;
grant usage,select on sequence app_private.operator_activity_id_seq to service_role;

create or replace function public.lothuus_operator_enabled(actor uuid) returns boolean
language sql stable security invoker set search_path='' as $$
 select exists(select 1 from app_private.operator_users where user_id=actor and enabled);
$$;
-- One-time, service-role-only enrollment used by the local setup command.
-- Never exposed through a website route and never re-enables a revoked operator.
create or replace function public.lothuus_operator_bootstrap(actor uuid) returns void
language plpgsql security invoker set search_path='' as $$
begin
 perform 1 from app_private.operator_settings where id for update;
 if exists(select 1 from app_private.operator_users where user_id=actor and email='kevin@webaanzee.be') then return; end if;
 if exists(select 1 from app_private.operator_users) then raise exception 'OPERATOR_ALREADY_CONFIGURED'; end if;
 insert into app_private.operator_users(user_id,email) values(actor,'kevin@webaanzee.be');
end; $$;
create or replace function public.lothuus_capacity_policy() returns jsonb
language sql stable security invoker set search_path='' as $$
 with h as (select public.lothuus_hosting_report() as report), s as (select *,expires_at is null or expires_at>now() as active from app_private.operator_settings where id)
 select jsonb_build_object('count',(report->>'count')::integer,'limit',case when s.active then coalesce(s.object_limit,(report->>'limit')::integer) else (report->>'limit')::integer end,
 'enforced',case when s.active then s.enforce_limit else true end) from h cross join s;
$$;
create or replace function app_private.hosting_check_capacity() returns trigger
language plpgsql security invoker set search_path='' as $$
declare policy jsonb;
begin
 if jsonb_array_length(new.body->'items')<=jsonb_array_length(old.body->'items') then return new; end if;
 perform 1 from app_private.hosting_account where id for update;
 if not found then raise exception 'HOSTING_ACCOUNT_UNAVAILABLE'; end if;
 perform 1 from app_private.operator_settings where id for share;
 policy:=public.lothuus_capacity_policy();
 if policy is null then raise exception 'HOSTING_ACCOUNT_UNAVAILABLE'; end if;
 if (policy->>'enforced')::boolean and jsonb_array_length(new.body->'items')>(policy->>'limit')::integer then raise exception 'HOSTING_OBJECT_LIMIT'; end if;
 return new;
end; $$;

-- Only server-selected metadata is accepted; never store passwords, tokens or form bodies.
create or replace function public.lothuus_record_activity(actor uuid,event_kind text,object_key text default null,event_title text default '') returns void
language plpgsql security invoker set search_path='' as $$
begin
 if event_kind not in ('owner_login','superadmin_login','photo_uploaded','capacity_denied') then raise exception 'INVALID_ACTIVITY'; end if;
 if event_kind='capacity_denied' then
  insert into app_private.operator_activity(actor_id,kind,title,dedupe_key)
   values(actor,event_kind,'Toevoeging geweigerd door objectlimiet',coalesce(actor::text,'system')||':capacity:'||to_char(now() at time zone 'UTC','YYYYMMDDHH24MI')) on conflict(dedupe_key) do nothing;
 else
  insert into app_private.operator_activity(actor_id,kind,object_id,title) values(actor,event_kind,left(object_key,100),left(event_title,180));
 end if;
end; $$;

create or replace function app_private.operator_audit_store() returns trigger
language plpgsql security invoker set search_path='' as $$
declare product record; changed jsonb; event_kind text; actor uuid;
begin
 actor:=nullif(current_setting('lothuus.actor',true),'')::uuid;
 for product in
  select o.value as previous,n.value as current from jsonb_array_elements(old.body->'items') o
  full join jsonb_array_elements(new.body->'items') n on o.value->>'id'=n.value->>'id'
  where o.value is distinct from n.value
 loop
  select coalesce(jsonb_agg(k),'[]') into changed from unnest(array['title','description','priceCents','priceUnset','publication','photos','materialGroup','productNumber','date','dimensions','condition','maker','material','category','editorReady']) k
   where product.previous->k is distinct from product.current->k;
  if product.previous is null then event_kind:='product_created';
  elsif product.current is null then event_kind:='product_removed';
  elsif product.previous->>'publication' is distinct from product.current->>'publication' then
   event_kind:=case product.current->>'publication' when 'published' then 'product_published' when 'archived' then 'product_archived' else 'product_unpublished' end;
  else event_kind:='product_updated'; end if;
  insert into app_private.operator_activity(actor_id,kind,object_id,title,details)
   values(actor,event_kind,coalesce(product.current->>'id',product.previous->>'id'),left(coalesce(product.current->>'title',product.previous->>'title',''),180),
   jsonb_build_object('fields',changed,'number',coalesce(product.current->>'productNumber',product.previous->>'productNumber')));
 end loop;
 if old.body->'settings' is distinct from new.body->'settings' then
  insert into app_private.operator_activity(actor_id,kind,title) values(actor,'website_settings_updated','Website-instellingen gewijzigd');
 end if;
 return new;
end; $$;
drop trigger if exists operator_audit_store on app_private.store;
create trigger operator_audit_store after update of body on app_private.store for each row execute function app_private.operator_audit_store();
create or replace function public.lothuus_commit_state_audited(expected_revision bigint,next_state jsonb,actor uuid) returns boolean
language plpgsql security invoker set search_path='' as $$
declare result boolean; previous_actor text;
begin
 previous_actor:=current_setting('lothuus.actor',true);
 perform set_config('lothuus.actor',actor::text,true);
 result:=public.lothuus_commit_state(expected_revision,next_state);
 perform set_config('lothuus.actor',coalesce(previous_actor,''),true);
 return result;
end; $$;

create or replace function public.lothuus_operator_report(actor uuid,before_id bigint default null) returns jsonb
language plpgsql stable security invoker set search_path='' as $$
declare result jsonb;
begin
 if not public.lothuus_operator_enabled(actor) then raise exception 'OPERATOR_FORBIDDEN'; end if;
 select jsonb_build_object('policy',public.lothuus_capacity_policy(),'settings',to_jsonb(s),
 'activity',coalesce((select jsonb_agg(to_jsonb(e)-'sequence' order by e.sequence desc) from (
   select a.id as sequence,a.id::text as id,at,actor_id,kind,object_id,title,details,
    case when a.actor_id is null then 'Systeem' when exists(select 1 from app_private.operator_users u where u.user_id=a.actor_id) then 'Kevin' else 'Eigenaar' end as actor
   from app_private.operator_activity a where before_id is null or id<before_id order by a.id desc limit 50
 ) e),'[]')) into result from app_private.operator_settings s where id;
 return result;
end; $$;
create or replace function public.lothuus_operator_policy(actor uuid,expected_version integer,enforce boolean,object_quota integer,until_at timestamptz,reason text) returns void
language plpgsql security invoker set search_path='' as $$
declare previous app_private.operator_settings;
begin
 if not public.lothuus_operator_enabled(actor) then raise exception 'OPERATOR_FORBIDDEN'; end if;
 if length(trim(reason))<3 or length(reason)>500 or (until_at is not null and until_at<=now()) then raise exception 'INVALID_POLICY'; end if;
 if object_quota is not null and (object_quota<1 or object_quota>100000) then raise exception 'INVALID_POLICY'; end if;
 -- Consistent order with the store trigger and hosting activation.
 perform 1 from app_private.hosting_account where id for update;
 select * into previous from app_private.operator_settings where id for update;
 if previous.version<>expected_version then raise exception 'OPERATOR_VERSION_CONFLICT'; end if;
 update app_private.operator_settings set enforce_limit=enforce,object_limit=object_quota,expires_at=until_at,version=version+1,updated_at=now() where id;
 insert into app_private.operator_activity(actor_id,kind,title,details) values(actor,'policy_changed','Objectrechten gewijzigd',jsonb_build_object('reason',trim(reason),'before',to_jsonb(previous),'after',jsonb_build_object('enforce_limit',enforce,'object_limit',object_quota,'expires_at',until_at)));
end; $$;
create or replace function public.lothuus_operator_activate(actor uuid,order_key uuid,receipt text,provisioned boolean) returns void
language plpgsql security invoker set search_path='' as $$
declare operator_email text; was_active boolean;
begin
 select email into operator_email from app_private.operator_users where user_id=actor and enabled;
 if operator_email is null then raise exception 'OPERATOR_FORBIDDEN'; end if;
 perform 1 from app_private.hosting_account where id for update;
 select status='active' into was_active from app_private.hosting_orders where id=order_key;
 perform public.lothuus_hosting_activate(order_key,operator_email,receipt,provisioned);
 if not coalesce(was_active,false) then
  insert into app_private.operator_activity(actor_id,kind,object_id,title) values(actor,'payment_activated',order_key::text,'Betaling bevestigd en pakket geactiveerd');
 end if;
end; $$;

